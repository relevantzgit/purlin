"""What model routing must hold: `specs/instructions/model_routing.md`.

Each skill's tier, the format's two tables, the project skill it gives, where
the tier and the model are read, the hand-off, its message, the build skill's
line, the runner agent and the agent's pointer are read as text. A copy with
one thing changed is read through `copy_without` or by passing the changed
text, and the files on disk are never touched.
"""

import re

import skill_checks
from skill_checks import (copy_without, flat, sentences_with, skill_files,
                          skill_path, under_heading)

FORMAT = 'references/formats/routing_format.md'
AGENT = 'agents/purlin.md'
RUNNER = 'agents/runner.md'
HAND_OFF = '"The hand-off"'
ROUTED = ('anchor', 'audit', 'build', 'drift', 'init', 'sign', 'spec',
          'spec-from-code', 'status', 'test')
TIERS = ('fast', 'balanced', 'performance')


def front_matter(text):
    """The front matter of a skill or agent: the lines between its `---`."""
    found = re.match(r'---\n(.*?)\n---\n', text, re.S)
    return found.group(1) if found else ''


def tier_of(text):
    """The `tier:` a skill's front matter names, or None."""
    found = re.search(r'^tier: *(\S+) *$', front_matter(text), re.M)
    return found.group(1) if found else None


def table_tiers(text):
    """`{skill: tier}` from the format's table of skills."""
    part = under_heading(text, 'The two tables')
    return dict(re.findall(r'^\| `([\w-]+)` \| `(%s)` \|$' % '|'.join(TIERS),
                           part, re.M))


def wrong_tiers(texts, table):
    """Each skill of `{name: text}` whose tier is not the table's; `route`
    is wrong where it names any."""
    wrong = [name for name, text in texts.items()
             if name != 'route' and tier_of(text) != table.get(name)]
    if 'route' in texts and tier_of(texts['route']) is not None:
        wrong.append('route')
    return sorted(wrong)


def skill_texts():
    return {name: skill_checks.read(skill_path(name))
            for name in ROUTED + ('route',)}


def split(text):
    return re.split(r'(?<=\.)\s+(?=[A-Z`*/])', text)


def part(heading):
    return flat(under_heading(skill_checks.read(FORMAT), heading))


# purlin: model_routing PROOF-1
def test_each_skill_names_the_tier_the_table_gives_it():
    table = table_tiers(skill_checks.read(FORMAT))
    assert sorted(table) == sorted(ROUTED)
    assert wrong_tiers(skill_texts(), table) == []


# purlin: model_routing PROOF-2
def test_a_test_skill_on_another_tier_is_listed():
    table = table_tiers(skill_checks.read(FORMAT))
    texts = skill_texts()
    texts['test'] = texts['test'].replace('tier: fast', 'tier: performance')
    assert wrong_tiers(texts, table) == ['test']


# purlin: model_routing PROOF-3
def test_the_format_gives_each_tier_its_default_model():
    rows = re.findall(r'^\| `(%s)` \| `([\w.-]+)` \|$' % '|'.join(TIERS),
                      under_heading(skill_checks.read(FORMAT),
                                    'The two tables'), re.M)
    assert rows == [('fast', 'haiku'), ('balanced', 'sonnet'),
                    ('performance', 'opus')]


def project_skill_problems(text):
    """What the format's project skill lacks: the path, the `model:` line,
    the description's mark, `purlin:<skill>` and `$ARGUMENTS`."""
    section = under_heading(text, 'The project skills')
    problems = [] if '.claude/skills/<skill>/SKILL.md' in section else [
        'path missing']
    found = re.search(r'```markdown\n(.*?)\n```', section, re.S)
    if not found:
        return problems + ['no fenced block']
    block = found.group(1)
    head = front_matter(block + '\n')
    body = block[block.find('---', 3) + 3:] if block.startswith('---') else ''
    if not re.search(r'^model: ', head, re.M):
        problems.append('model: missing')
    if not re.search(r'^description: Generated by purlin:route', head, re.M):
        problems.append('description mark missing')
    for name in ('purlin:<skill>', '$ARGUMENTS'):
        if name not in body:
            problems.append('%s missing' % name)
    return problems


# purlin: model_routing PROOF-4
def test_the_format_gives_the_project_skill():
    assert project_skill_problems(skill_checks.read(FORMAT)) == []


# purlin: model_routing PROOF-5
def test_a_project_skill_without_its_arguments_is_reported():
    text = skill_checks.read(FORMAT).replace('$ARGUMENTS', '')
    assert project_skill_problems(text) == ['$ARGUMENTS missing']


def first_of(sentence, one, other):
    return sentence.index(one) < sentence.index(other)


# purlin: model_routing PROOF-6
def test_the_skills_entry_and_the_local_tiers_are_read_first():
    sentences = split(part('The project skills'))
    tier = [s for s in sentences if '`skills`' in s and '`tier:`' in s]
    assert tier and first_of(tier[0], '`skills`', '`tier:`')
    model = [s for s in sentences if '`.purlin/routing.local.json`' in s
             and '`.purlin/routing.json`' in s]
    assert model and first_of(model[0], '`.purlin/routing.local.json`',
                              '`.purlin/routing.json`')


# purlin: model_routing PROOF-7
def test_a_skill_another_skill_runs_goes_to_a_runner_subagent():
    sentences = split(part('The hand-off'))
    assert [s for s in sentences if 'another skill' in s
            and '`purlin:runner`' in s and 'subagent' in s]
    assert [s for s in sentences if 'runs here' in s]


MESSAGE = ('Command:', 'Goal:', 'Model:', 'Context:', 'Previous:', 'Read:',
           'Rules:', 'Return:')


def message_problems(text):
    """The fields of the hand-off message missing from, or out of order in,
    the fenced block of the format's part "The hand-off message"."""
    found = re.search(r'```\n(.*?)\n```',
                      under_heading(text, 'The hand-off message'), re.S)
    if not found:
        return ['no fenced block']
    opens = [line.split()[0] for line in found.group(1).splitlines()
             if line.split() and line.split()[0] in MESSAGE]
    missing = ['%s missing' % name for name in MESSAGE if name not in opens]
    return missing or ([] if opens == list(MESSAGE) else ['out of order'])


# purlin: model_routing PROOF-8
def test_the_hand_off_message_has_its_eight_lines_in_order():
    assert message_problems(skill_checks.read(FORMAT)) == []


# purlin: model_routing PROOF-9
def test_a_message_without_its_goal_is_reported():
    text = '\n'.join(line for line in skill_checks.read(FORMAT).splitlines()
                     if not line.startswith('Goal:'))
    assert message_problems(text) == ['Goal: missing']


def hand_off_problems():
    """The build skill where its part "Running them" names no hand-off, and
    each other skill that names it."""
    build = skill_path('build')
    lines = under_heading(skill_checks.read(build), 'Running them').splitlines()
    problems = [] if [line for line in lines
                      if FORMAT in line and HAND_OFF in line] else [build]
    return problems + [rel for rel in skill_files()
                       if rel != build and HAND_OFF in skill_checks.read(rel)]


# purlin: model_routing PROOF-10
def test_only_the_build_skill_names_the_hand_off():
    assert hand_off_problems() == []


# purlin: model_routing PROOF-11
def test_a_build_skill_without_the_line_is_reported():
    rel = skill_path('build')
    line = [line for line in skill_checks.read(rel).splitlines()
            if FORMAT in line and HAND_OFF in line][0]
    with copy_without(rel, line):
        assert hand_off_problems() == ['skills/build/SKILL.md']


# purlin: model_routing PROOF-12
def test_the_runner_has_four_tools_and_does_not_route_again():
    text = skill_checks.read(RUNNER)
    assert re.search(r'^tools: Skill, Read, Bash, PowerShell$',
                     front_matter(text), re.M)
    assert 'do not route again' in text


# purlin: model_routing PROOF-13
def test_the_agent_points_at_the_format_and_does_not_restate_it():
    text = skill_checks.read(AGENT)
    routing = flat(under_heading(text, 'Model routing'))
    for name in (FORMAT, '"The project skills"', HAND_OFF):
        assert name in routing, name
    assert not [line for line in text.splitlines()
                if line.lstrip().startswith('Previous:')]


